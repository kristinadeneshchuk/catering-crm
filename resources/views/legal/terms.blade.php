    <li>Якщо раціон не відповідає замовленню або має ознаки зіпсованості, повідомте менеджера у день
        отримання — ми замінимо страву або повернемо вартість.</li>
    <li>Передплата за невикористані дні раціону повертається у повному обсязі за вимогою Клієнта.</li>
