<h2>2. Опис послуг</h2>
<p>U-fit надає такі послуги:</p>
<ul>
    <li>Приготування готових раціонів харчування різної калорійності і складу</li>
    <li>Доставка раціонів за вказаною адресою у визначений час</li>
    <li>Консультації менеджерів через телефон, Telegram, Viber, Instagram</li>
</ul>

<h2>3. Замовлення</h2>
<ul>
    <li>Замовлення можна оформити через дзвінок, переписку в месенджері або інший наданий канал.</li>
    <li>Замовлення вважається підтвердженим після узгодження тарифу, дат, адреси доставки та оплати
