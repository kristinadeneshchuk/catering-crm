    <li>Зміну дати доставки або тимчасову паузу слід погоджувати не пізніше ніж за 24 години до доставки.</li>
</ul>

<h2>4. Оплата</h2>
<ul>
    <li>Оплата здійснюється безготівковим переказом на банківський рахунок, через посилання на оплату
        у захищеному платіжному сервісі або іншим погодженим способом.</li>
    <li>Чек або підтвердження оплати надається на запит.</li>
</ul>

<h2>5. Доставка</h2>
<ul>
    <li>Доставка здійснюється у часовому інтервалі, погодженому з менеджером.</li>
    <li>Клієнт зобовʼязаний забезпечити можливість прийняти доставку у вказаний час.</li>
    <li>У разі відсутності Клієнта на місці доставки без попередження, повторна доставка може бути платною
        або раціон вважається доставленим.</li>
</ul>

