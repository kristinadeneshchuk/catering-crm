<?php

namespace App\Support;

/**
 * Коментар для курʼєра — лише як передати (консьєрж, з рук у руки, під дверима,
 * охорона) і орієнтир. Дієта, калораж, мова клієнта, побажання до меню курʼєру
 * не потрібні (власник 16.11): такі речення з тексту прибираємо.
 */
class CourierNote
{
    private const NOT_FOR_COURIER = '/свинин|субпродукт|лактоз|глютен|алерг|не\s*(їсть|ест|вживає|любить)|без\s+(мʼяса|м\'яса|мяса|цукру|сахара|молочн|цибул|часник|риб|горіх)|чорнослив|ккал|калор|меню|дієт|диет|раціон|рацион|веган|вегетар|англомов|англоязыч|мовою|українською|російською|бжу|бжв|білк|белк/ui';

    public static function clean(?string $text): ?string
    {
        $text = trim((string) $text);
        if ($text === '') {
            return null;
        }

        $kept = collect(preg_split('/(?<=[.!?;])\s+|\n+/u', $text))
            ->map(fn ($s) => trim($s))
            ->filter(fn ($s) => $s !== '' && ! preg_match(self::NOT_FOR_COURIER, $s))
            ->implode(' ');

        return $kept !== '' ? $kept : null;
    }
}
