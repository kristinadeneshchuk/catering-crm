    /** @return array<string, int[]> slug → id продуктів, що підпадають під групу */
    public static function match(iterable $ingredients): array
    {
        $out = [];
        foreach (self::all() as $slug => $g) {
            $out[$slug] = [];
            foreach ($ingredients as $ing) {
                $name = mb_strtolower(trim((string) $ing->name));
                if (!preg_match('/' . $g['include'] . '/iu', $name)) continue;
                if (!empty($g['exclude']) && preg_match('/' . $g['exclude'] . '/iu', $name)) continue;
                $out[$slug][] = (int) $ing->id;
            }
        }

        return $out;
    }
