    /** Нижній регістр, апострофи й дефіси геть, пробіли схлопнуті. */
    public function normalize(string $value): string
    {
        $value = Str::lower(trim($value));
        $value = str_replace(['ʼ', '’', '`', '´'], "'", $value);
        $value = preg_replace('~[^\p{L}\p{N}\'\s-]+~u', ' ', $value);

        return trim(preg_replace('~\s+~u', ' ', $value));
    }

    /**
     * Слова запиту. Односимвольні відкидаються: вони збігаються з усім.
     *
     * @return list<string>
     */
    public function tokens(string $value): array
    {
        $words = preg_split('~[\s/,]+~u', $this->normalize($value), -1, PREG_SPLIT_NO_EMPTY) ?: [];

        return array_values(array_filter($words, fn (string $w) => mb_strlen($w) > 1));
    }

    /**
     * Усі написання одного слова, які варто спробувати в базі.
     *
     * @return list<string>
     */
    public function variants(string $token): array
    {
        $variants = [$token];

        if ($brand = $this->brand($token)) {
            $variants[] = $brand;
        }

        if ($synonym = $this->synonym($token)) {
            $variants[] = $synonym;
        }

        if ($layout = $this->layout($token)) {
            $variants[] = $layout;
            // Розкладку могли не перемкнути на назві бренду: «,ji» → «бош» → «bosch».
            if ($brandOfLayout = $this->brand($layout)) {
                $variants[] = $brandOfLayout;
            }
            if ($synonymOfLayout = $this->synonym($layout)) {
                $variants[] = $synonymOfLayout;
            }
        }

        if ($translit = $this->translit($token)) {
            $variants[] = $translit;
        }

        // Дефіси й пробіли в артикулах ставлять як заманеться: hr2470 / hr-2470.
        $bare = str_replace(['-', "'"], '', $token);
        if ($bare !== $token && mb_strlen($bare) > 1) {
            $variants[] = $bare;
        }

        return array_values(array_unique(array_filter($variants)));
    }

    /** Слово в латиниці, яке насправді набране в українській розкладці. */
    public function layout(string $token): ?string
    {
        // Кирилицю перекладати нікуди — вона вже в потрібній розкладці.
        if (preg_match('~\p{Cyrillic}~u', $token)) {
            return null;
        }

        $out = '';
        foreach (mb_str_split($token) as $char) {
            $out .= self::LAYOUT[$char] ?? $char;
        }

        // Якщо жодна літера не змінилась — це просто латинське слово (bosch).
        return $out === $token ? null : $out;
    }

    /** Кирилиця → латиниця; для латинського слова повертає null. */
    public function translit(string $token): ?string
    {
        if (! preg_match('~\p{Cyrillic}~u', $token)) {
            return null;
        }

        return strtr($token, self::TRANSLIT) ?: null;
    }

    /** Кириличне написання бренду → те, як він записаний у базі. */
    public function brand(string $token): ?string
    {
        return self::BRANDS[$token] ?? null;
    }

    /** Розмовна або російська назва → слово з каталогу. */
    public function synonym(string $token): ?string
    {
        return self::SYNONYMS[$token] ?? null;
    }

    /**
     * Чи схожі слова з точністю до одруківки.
     *
     * Поріг залежить від довжини: у «бур» одна помилкова літера — це вже інше
     * слово, у «перфоратор» — звичайна одруківка. Levenshtein працює по байтах,
     * тому кирилицю спершу переганяємо в латиницю, де літера = байт.
     */
    public function looksLike(string $a, string $b): bool
    {
        $a = $this->translit($a) ?? $a;
        $b = $this->translit($b) ?? $b;

        $length = min(strlen($a), strlen($b));

        if ($length < 4) {
            return $a === $b;
        }

        return levenshtein($a, $b) <= ($length <= 6 ? 1 : 2);
    }
