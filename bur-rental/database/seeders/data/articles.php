- **Балконна плита.** Бурити впритул до неї не варто — ослаблення в місці защемлення.

## Шлам

Вода з бетонним пилом тече вниз і потрапляє на все, що під стіною. Це не «трохи бризок»: за отвір набирається кілька літрів сірої рідини, яка засихає намертво.

Плівка на підлогу, ганчірка під установку і [пилосос](/instrument/karcher-wd-6) у режимі вологого прибирання поруч — стандартний набір. Прибирати засохлий шлам із плитки вдвічі довше, ніж не дати йому розтектися.

